  /* ---------- Экспорт/импорт избранного ---------- */
  function exportFavorites() {
    const data = { version: 1, favorites: [...state.favorites] };
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `waifudex-favorites-${new Date().toISOString().slice(0, 10)}.json`;
    a.click();
    URL.revokeObjectURL(url);
    toast(`Экспортировано: ${state.favorites.size}`);
  }

  function importFavorites(file) {
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const data = JSON.parse(reader.result);
        const ids = Array.isArray(data) ? data : data.favorites;
        if (!Array.isArray(ids)) throw new Error("Неверный формат");
        const valid = ids.map(String).filter((id) => byId.has(id));
        state.favorites = new Set(valid);
        storage.set("waifudex:favorites", [...state.favorites]);
        updateCounters(true);
        toast(`Импортировано: ${valid.length}`);
        renderCatalog();
      } catch {
        toast("Не удалось прочитать файл");
      }
    };
    reader.readAsText(file);
  }

