  function router() {
    const hash = location.hash.replace(/^#\/?/, "");
    const [page, param] = hash.split("/");
    const prev = currentRoute;
    currentRoute = hash;
    closeMenu();
    if (!lb.root.hidden) closeLightbox();

    switch (page) {
      case "":
      case "home":
        document.title = "WaifuDex — каталог аниме-героинь";
        renderHome(); showView("home"); setActiveNav("home");
        break;
      case "characters":
        document.title = "Персонажи · WaifuDex";
        if (state.filter === "favorites") state.filter = "all";
        renderCatalog(); showView("catalog"); setActiveNav("characters");
        break;
      case "favorites":
        document.title = "Избранное · WaifuDex";
        state.filter = "favorites";
        renderCatalog(); showView("catalog"); setActiveNav("favorites");
        break;
      case "anime":
        document.title = "Аниме · WaifuDex";
        renderAnime(); showView("anime"); setActiveNav("anime");
        break;
      case "character":
        renderCharacter(decodeURIComponent(param || "")); showView("character"); setActiveNav("characters");
        break;
      default:
        location.hash = "#/";
        return;
    }
    if (prev !== hash) window.scrollTo({ top: 0, behavior: "auto" });
  }

