  function openLightbox(c, index = 0) {
    if (!c?.images?.length) return;
    lb.char = c;
    lb.lastFocus = document.activeElement;
    lb.thumbs.innerHTML = c.images.map((_, i) =>
      `<button data-thumb="${i}" aria-label="Изображение ${i + 1}">${imgTag(c, i, "", "")}</button>`).join("");
    const single = c.images.length < 2;
    lb.prev.hidden = lb.next.hidden = single;
    lb.root.hidden = false;
    lb.root.classList.remove("is-closing");
    document.body.classList.add("no-scroll");
    showSlide(index, 0);
    $(".lightbox__close", lb.root).focus();
  }

  function showSlide(index, dir = 1) {
    const c = lb.char;
    const n = c.images.length;
    lb.index = (index + n) % n;
    const apply = () => {
      lb.img.dataset.char = c.id;
      lb.img.dataset.index = lb.index;
      delete lb.img.dataset.fallback;
      lb.img.src = c.images[lb.index];
      lb.img.alt = `${c.name} — изображение ${lb.index + 1}`;
      lb.caption.textContent = `${c.name} · ${lb.index + 1} / ${n}`;
      $$("[data-thumb]", lb.thumbs).forEach((t, i) => t.classList.toggle("is-active", i === lb.index));
      $(`[data-thumb="${lb.index}"]`, lb.thumbs)?.scrollIntoView({ block: "nearest", inline: "center", behavior: "smooth" });
      requestAnimationFrame(() => lb.img.classList.remove("is-switching-next", "is-switching-prev"));
    };
    if (dir === 0) return apply();
    lb.img.classList.add(dir > 0 ? "is-switching-next" : "is-switching-prev");
    setTimeout(apply, 180);
  }

  function closeLightbox() {
    if (lb.root.hidden) return;
    lb.root.classList.add("is-closing");
    setTimeout(() => {
      lb.root.hidden = true;
      lb.root.classList.remove("is-closing");
      document.body.classList.remove("no-scroll");
      lb.lastFocus?.focus?.();
    }, 280);
  }

