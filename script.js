  function getFiltered() {
    const q = normalize(state.query);
    let list = CHARACTERS.filter((c) => {
      if (state.filter === "popular" && !isPopular(c)) return false;
      if (state.filter === "favorites" && !state.favorites.has(String(c.id))) return false;
      if (state.anime && c.anime !== state.anime) return false;
      if (state.tag && !(c.tags || []).includes(state.tag)) return false;
      if (!q) return true;
      const hay = normalize([c.name, c.nameEn, c.anime, c.animeRu, ...(c.tags || [])].join(" "));
      return q.split(/\s+/).every((word) => hay.includes(word));
    });

    const collator = new Intl.Collator("ru", { sensitivity: "base" });
    const sorters = {
      popularity: (a, b) => (b.popularity || 0) - (a.popularity || 0),
      name: (a, b) => collator.compare(a.name, b.name),
      anime: (a, b) => collator.compare(a.anime, b.anime) || collator.compare(a.name, b.name),
    };
    return list.sort(sorters[state.sort] || sorters.popularity);
  }

